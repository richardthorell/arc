import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { afterEach, describe, expect, it, vi } from 'vitest';

import type { ArcProjectCandidate } from '../common/projectTypes';
import { editorCommandBuildDirectory, EditorCommandTargetGraph } from './editorCommandTargetGraph';

const temporary: string[] = [];
function project(): ArcProjectCandidate {
  const projectRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'arc-editor-build-'));
  temporary.push(projectRoot);
  return {
    projectRoot,
    descriptorPath: path.join(projectRoot, 'Test.arcproject'),
    writable: true,
    descriptor: {
      guid: 'editor-project',
      paths: { build: 'Build', saved: 'Saved' },
      modules: [{ id: 'editor-module', kind: 'editor', target: 'MyEditor', enabled: true }],
    },
  } as ArcProjectCandidate;
}

function reply(buildDir: string, moduleDependencies = ['runtime']): void {
  const dir = path.join(buildDir, '.cmake', 'api', 'v1', 'reply');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index-20261117-120000.json'), JSON.stringify({
    cmake: { generator: { name: 'Ninja' } },
    reply: { 'codemodel-v2': { jsonFile: 'codemodel-v2-file.json' } },
  }));
  fs.writeFileSync(path.join(dir, 'codemodel-v2-file.json'), JSON.stringify({
    configurations: [{ name: '', targets: [
      { id: 'editor', name: 'MyEditor', jsonFile: 'target-editor.json' },
      { id: 'runtime', name: 'MyRuntime', jsonFile: 'target-runtime.json' },
      { id: 'unrelated', name: 'OtherTest', jsonFile: 'target-test.json' },
    ] }],
  }));
  fs.writeFileSync(path.join(dir, 'target-editor.json'), JSON.stringify({
    id: 'editor', name: 'MyEditor', type: 'MODULE_LIBRARY',
    dependencies: moduleDependencies.map((id) => ({ id })),
    artifacts: [{ path: 'MyEditor.so' }],
  }));
  fs.writeFileSync(path.join(dir, 'target-runtime.json'), JSON.stringify({
    id: 'runtime', name: 'MyRuntime', type: 'STATIC_LIBRARY', artifacts: [{ path: 'libMyRuntime.a' }],
  }));
  fs.writeFileSync(path.join(dir, 'target-test.json'), JSON.stringify({
    id: 'unrelated', name: 'OtherTest', type: 'EXECUTABLE', artifacts: [{ path: 'OtherTest' }],
  }));
}

afterEach(() => {
  for (const root of temporary.splice(0)) fs.rmSync(root, { force: true, recursive: true });
});

describe('BM6 normal editor command CMake graph', () => {
  it('queries Build/default before the first configure and captures a reply generated by that command', () => {
    const active = project();
    const buildDir = editorCommandBuildDirectory(active)!;
    const publish = vi.fn();
    const graph = EditorCommandTargetGraph.forProject(active, 'Debug', publish)!;
    graph.prepare();
    expect(fs.existsSync(path.join(buildDir, '.cmake', 'api', 'v1', 'query', 'codemodel-v2'))).toBe(true);
    expect(publish).not.toHaveBeenCalled();
    reply(buildDir);

    const artifact = path.join(buildDir, 'MyEditor.so');
    graph.observe(`  MyEditor.vcxproj -> ${artifact.slice(0, artifact.length / 2)}`, 'stdout');
    graph.observe(`${artifact.slice(artifact.length / 2)}\n`, 'stdout');
    graph.observe(`  MyEditor.vcxproj -> ${artifact}\n`, 'stdout');
    graph.finish();

    expect(publish).toHaveBeenCalledTimes(2);
    const result = publish.mock.lastCall?.[0];
    expect(result).toMatchObject({
      revision: 2, configuration: 'Debug', rootTargetId: 'editor',
      nodes: [
        { id: 'editor', dependencies: ['runtime'], artifactObservedAt: expect.any(String) },
        { id: 'runtime', dependencies: [] },
      ],
    });
    expect(result.nodes.some((node: { name: string }) => node.name === 'OtherTest')).toBe(false);
    expect(result.nodes[0]).not.toHaveProperty('satisfiedAt');
  });

  it('shows the configured module subtree but does not claim success when incremental output is silent', () => {
    const active = project();
    const buildDir = editorCommandBuildDirectory(active)!;
    reply(buildDir);
    const publish = vi.fn();
    const graph = EditorCommandTargetGraph.forProject(active, 'RelWithDebInfo', publish)!;
    graph.prepare();
    graph.observe('ninja: no work to do.\n', 'stdout');
    graph.finish();
    expect(publish).toHaveBeenCalledTimes(1);
    expect(publish.mock.lastCall?.[0].nodes.every((node: { artifactObservedAt?: string }) =>
      !node.artifactObservedAt)).toBe(true);
  });

  it('publishes a changed graph after an explicit configure without reusing obsolete artifacts', () => {
    const active = project();
    const buildDir = editorCommandBuildDirectory(active)!;
    reply(buildDir);
    const publish = vi.fn();
    const graph = EditorCommandTargetGraph.forProject(active, 'Debug', publish)!;
    graph.prepare();
    graph.observe(`MyEditor -> ${path.join(buildDir, 'MyEditor.so')}\n`, 'stdout');
    reply(buildDir, []);
    graph.finish();
    const last = publish.mock.lastCall?.[0];
    expect(last.revision).toBe(3);
    expect(last.nodes[0].dependencies).toEqual([]);
    expect(last.nodes[0].artifactObservedAt).toBeUndefined();
  });

  it('rejects build roots outside the project and symlinks within the project', () => {
    const active = project();
    active.descriptor.paths.build = '../../outside';
    expect(editorCommandBuildDirectory(active)).toBeNull();
    active.descriptor.paths.build = 'Build';
    if (process.platform !== 'win32') {
      const outside = fs.mkdtempSync(path.join(os.tmpdir(), 'arc-unsafe-build-'));
      temporary.push(outside);
      fs.symlinkSync(outside, path.join(active.projectRoot, 'Build'), 'dir');
      expect(editorCommandBuildDirectory(active)).toBeNull();
    }
  });

  it('does not invent roots for disabled or missing editor modules', () => {
    const active = project();
    active.descriptor.modules[0].enabled = false;
    expect(EditorCommandTargetGraph.forProject(active, 'Debug', vi.fn())).toBeNull();
    active.descriptor.modules = [];
    expect(EditorCommandTargetGraph.forProject(active, 'Debug', vi.fn())).toBeNull();
  });
});
